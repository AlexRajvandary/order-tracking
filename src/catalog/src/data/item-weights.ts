export type WeightCategoryId =
  | "clothing"
  | "accessories"
  | "electronics"
  | "home"
  | "packaging"
  | "other";

export type WeightValue = string | null;

export type WeightItem = {
  name: string;
  male?: WeightValue;
  female?: WeightValue;
  child?: WeightValue;
  weight?: WeightValue;
};

export type WeightGroup = {
  category: WeightCategoryId;
  title: string;
  gendered: boolean;
  items: WeightItem[];
};

const gendered = (
  category: WeightCategoryId,
  title: string,
  items: Array<[string, WeightValue?, WeightValue?, WeightValue?]>,
): WeightGroup => ({ category, title, gendered: true, items: items.map(([name, male = null, female = null, child = null]) => ({ name, male, female, child })) });

const simple = (
  category: WeightCategoryId,
  title: string,
  items: Array<[string, WeightValue]>,
): WeightGroup => ({ category, title, gendered: false, items: items.map(([name, weight]) => ({ name, weight })) });

