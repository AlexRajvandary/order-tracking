/**
 * Stage 2: denormalized luibags JSON → SQL for products DB.
 *
 * Resolves FKs by name/slug:
 *   - brands by Brand slug
 *   - shops by shopName / slug
 *   - categories under bags (creates missing subcategories, sets CategoryId)
 *
 * Usage:
 *   node scripts/import-luibags-json.mjs [inputJson] [outputSql]
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { randomUUID } from "node:crypto";
import {
  BAGS_PARENT_SLUG,
  CANONICAL_BAG_SUBCATEGORIES,
  resolveBagSubcategory,
} from "./luibags-category-map.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const inputPath =
  process.argv[2] || path.join(__dirname, "data", "luibags.json");
const outputPath =
  process.argv[3] || path.join(__dirname, "data", "luibags-import.sql");

const data = JSON.parse(fs.readFileSync(inputPath, "utf8"));
const products = data.products || [];

function esc(s) {
  if (s == null || s === "") return "NULL";
  return "'" + String(s).replace(/'/g, "''") + "'";
}

function num(n) {
  if (n == null || !Number.isFinite(Number(n))) return "NULL";
  return String(Number(n));
}

function slugify(name) {
  let slug = String(name).trim().toLowerCase();
  slug = slug.replace(/[^a-z0-9\u0400-\u04FF]+/gi, "-");
  slug = slug.replace(/-+/g, "-").replace(/^-|-$/g, "");
  return slug || randomUUID().replace(/-/g, "").slice(0, 8);
}

function productSlug(name, sku) {
  const base = slugify(name).slice(0, 160);
  const suffix = (sku || randomUUID())
    .toString()
    .replace(/[^a-zA-Z0-9-]/g, "")
    .slice(-12);
  return `${base}-${suffix}`.toLowerCase();
}

const brandName = data.brand || "Louis Vuitton";
const brandSlug = slugify(brandName);
const brandId = randomUUID();

const shopMeta = new Map();
for (const p of products) {
  if (!p.shopName) continue;
  const slug = p.shopSlug || slugify(p.shopName);
  if (!shopMeta.has(slug)) {
    shopMeta.set(slug, { id: randomUUID(), name: p.shopName, slug });
  }
}

const categoryStats = new Map();
let withSubcategory = 0;
let withParentOnly = 0;
for (const p of products) {
  const resolved = resolveBagSubcategory(p.categories);
  p._category = resolved;
  if (resolved.isParent) withParentOnly += 1;
  else withSubcategory += 1;
  categoryStats.set(
    resolved.slug,
    (categoryStats.get(resolved.slug) || 0) + 1,
  );
}

const now = new Date().toISOString();
const lines = [];
lines.push("-- Generated by import-luibags-json.mjs");
lines.push(`-- Source: ${data.source || inputPath}`);
lines.push(`-- Products: ${products.length}`);
lines.push(`-- Subcategory: ${withSubcategory}, parent bags only: ${withParentOnly}`);
lines.push(`-- GeneratedAt: ${data.generatedAt || now}`);
lines.push("BEGIN;");
lines.push("");

lines.push("-- Brand (insert if missing by slug)");
lines.push(`INSERT INTO brands (
  "Id", "Name", "Slug", "Description", "LogoUrl",
  "SortOrder", "IsActive", "CreatedAt", "UpdatedAt", "IsDeleted", "DeletedAt"
)
SELECT
  '${brandId}'::uuid,
  ${esc(brandName)},
  ${esc(brandSlug)},
  NULL, NULL,
  0, TRUE, '${now}'::timestamptz, NULL, FALSE, NULL
WHERE NOT EXISTS (
  SELECT 1 FROM brands WHERE "Slug" = ${esc(brandSlug)} AND "IsDeleted" = FALSE
);`);
lines.push("");

lines.push("-- Shops (insert if missing by slug)");
for (const shop of shopMeta.values()) {
  lines.push(`INSERT INTO shops (
  "Id", "Name", "Slug", "WebsiteUrl", "Description",
  "SortOrder", "IsActive", "CreatedAt", "UpdatedAt", "IsDeleted", "DeletedAt"
)
SELECT
  '${shop.id}'::uuid,
  ${esc(shop.name)},
  ${esc(shop.slug)},
  NULL, NULL,
  0, TRUE, '${now}'::timestamptz, NULL, FALSE, NULL
WHERE NOT EXISTS (
  SELECT 1 FROM shops WHERE "Slug" = ${esc(shop.slug)} AND "IsDeleted" = FALSE
);`);
}
lines.push("");

lines.push("-- Bag subcategories under parent slug=bags (create missing)");
let sortOrder = 100;
for (const cat of CANONICAL_BAG_SUBCATEGORIES) {
  const id = randomUUID();
  sortOrder += 1;
  lines.push(`INSERT INTO categories (
  "Id", "ParentId", "Name", "Slug", "Description", "ImageUrl",
  "SortOrder", "IsPopular", "IsActive", "CreatedAt", "UpdatedAt", "IsDeleted", "DeletedAt"
)
SELECT
  '${id}'::uuid,
  (SELECT "Id" FROM categories WHERE "Slug" = ${esc(BAGS_PARENT_SLUG)} AND "ParentId" IS NULL AND "IsDeleted" = FALSE LIMIT 1),
  ${esc(cat.name)},
  ${esc(cat.slug)},
  NULL, NULL,
  ${sortOrder}, FALSE, TRUE, '${now}'::timestamptz, NULL, FALSE, NULL
WHERE EXISTS (
  SELECT 1 FROM categories WHERE "Slug" = ${esc(BAGS_PARENT_SLUG)} AND "ParentId" IS NULL AND "IsDeleted" = FALSE
)
AND NOT EXISTS (
  SELECT 1 FROM categories c
  WHERE c."Slug" = ${esc(cat.slug)}
    AND c."IsDeleted" = FALSE
    AND c."ParentId" = (
      SELECT "Id" FROM categories
      WHERE "Slug" = ${esc(BAGS_PARENT_SLUG)} AND "ParentId" IS NULL AND "IsDeleted" = FALSE
      LIMIT 1
    )
);`);
}
lines.push("");

let inserted = 0;
for (const p of products) {
  const sku = p.sku ? String(p.sku).slice(0, 100) : null;
  const id = randomUUID();
  const slug = productSlug(p.name, sku);
  const condition = p.condition === "new" ? "New" : "Used";
  const shopSlug = p.shopSlug || (p.shopName ? slugify(p.shopName) : null);
  const cat = p._category;

  const descParts = [];
  if (p.sellerName) descParts.push(`Продавец: ${p.sellerName}`);
  if (p.conditionLabel) descParts.push(`Состояние: ${p.conditionLabel}`);
  if (p.categories?.length) {
    descParts.push(`Категории источника: ${p.categories.join(", ")}`);
  }
  if (cat?.matchedLabel) {
    descParts.push(`Подкатегория: ${cat.name} (из «${cat.matchedLabel}»)`);
  }
  if (p.zenplusUrl && p.zenplusUrl !== p.sourceUrl) {
    descParts.push(`ZenPlus: ${p.zenplusUrl}`);
  }
  const description = descParts.length ? descParts.join("\n") : null;

  const categoryIdSql = cat.isParent
    ? `(SELECT "Id" FROM categories
       WHERE "Slug" = ${esc(BAGS_PARENT_SLUG)}
         AND "ParentId" IS NULL
         AND "IsDeleted" = FALSE
       LIMIT 1)`
    : `(SELECT c."Id" FROM categories c
       INNER JOIN categories p ON p."Id" = c."ParentId"
       WHERE c."Slug" = ${esc(cat.slug)}
         AND p."Slug" = ${esc(BAGS_PARENT_SLUG)}
         AND c."IsDeleted" = FALSE
         AND p."IsDeleted" = FALSE
       LIMIT 1)`;

  lines.push(`INSERT INTO products (
  "Id", "Name", "Slug", "Description", "Sku", "Brand", "BrandId",
  "ShopId", "CategoryId", "Condition",
  "Price", "CurrencyCode", "OriginalPrice", "OriginalCurrencyCode",
  "ImageUrl", "SourceUrl", "IsActive",
  "CreatedAt", "UpdatedAt", "IsDeleted", "DeletedAt"
)
SELECT
  '${id}'::uuid,
  ${esc(p.name)},
  ${esc(slug)},
  ${esc(description)},
  ${esc(sku)},
  ${esc(p.brand || brandName)},
  (SELECT "Id" FROM brands WHERE "Slug" = ${esc(brandSlug)} AND "IsDeleted" = FALSE LIMIT 1),
  ${
    shopSlug
      ? `(SELECT "Id" FROM shops WHERE "Slug" = ${esc(shopSlug)} AND "IsDeleted" = FALSE LIMIT 1)`
      : "NULL"
  },
  ${categoryIdSql},
  ${esc(condition)},
  ${num(p.price)},
  ${esc(p.currencyCode || "RUB")},
  ${num(p.originalPrice)},
  ${esc(p.originalCurrencyCode)},
  ${esc(p.imageUrl)},
  ${esc(p.sourceUrl)},
  TRUE,
  '${now}'::timestamptz,
  NULL,
  FALSE,
  NULL
WHERE NOT EXISTS (
  SELECT 1 FROM products
  WHERE "IsDeleted" = FALSE
    AND (
      (${esc(sku)} IS NOT NULL AND "Sku" = ${esc(sku)})
      OR "Slug" = ${esc(slug)}
    )
);`);

  inserted += 1;
}

lines.push("");
lines.push("COMMIT;");
lines.push(
  `SELECT COUNT(*) AS total FROM products WHERE "Brand" = ${esc(brandName)} AND "IsDeleted" = FALSE;`,
);
lines.push(
  `SELECT c."Slug", COUNT(*) AS cnt
   FROM products p
   LEFT JOIN categories c ON c."Id" = p."CategoryId"
   WHERE p."Brand" = ${esc(brandName)} AND p."IsDeleted" = FALSE
   GROUP BY c."Slug"
   ORDER BY cnt DESC;`,
);

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, lines.join("\n"), "utf8");

console.log(
  JSON.stringify(
    {
      input: inputPath,
      output: outputPath,
      productsInJson: products.length,
      productsInSql: inserted,
      shops: shopMeta.size,
      brand: brandName,
      withSubcategory,
      withParentOnly,
      categoryStats: Object.fromEntries(
        [...categoryStats.entries()].sort((a, b) => b[1] - a[1]),
      ),
      newSubcategories: CANONICAL_BAG_SUBCATEGORIES.filter((c) => !c.existing).map(
        (c) => c.slug,
      ),
    },
    null,
    2,
  ),
);
